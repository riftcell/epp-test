// ---- Poll operations ----

// PollRead retrieves the next pending server message.
// Returns an error wrapping *EPPError{Code:1300} when the queue is empty.
func (a *GenericEPPAdapter) PollRead(ctx context.Context) (registrar.PollMessage, error) {
	var msg registrar.PollMessage

	err := a.withConn(ctx, func(conn net.Conn) error {
		clTRID := a.nextClTRID()
		env := eppxml.EPPEnvelope{
			Command: &eppxml.EPPCommand{
				Poll:   &eppxml.Poll{Op: "req"},
				ClTRID: clTRID,
			},
		}

		envResp, err := sendAndReceive(conn, env)
		if err != nil {
			return fmt.Errorf("epp: poll:req: %w", err)
		}

		if envResp.Response == nil {
			return fmt.Errorf("epp: poll:req: response missing <epp:response>")
		}

		// Result code 1300 means the queue is empty (RFC 5730 §3).
		// Return this as an EPPError so callers can distinguish empty queue from errors.
		if envResp.Response.Result.Code == 1300 {
			return &registrar.EPPError{
				Code:    1300,
				Message: envResp.Response.Result.Msg,
				Command: "epp:poll",
			}
		}

		if err := a.resultToError(envResp.Response.Result, "epp:poll"); err != nil {
			return err
		}

		if envResp.Response.MsgQ != nil {
			msg.ID = envResp.Response.MsgQ.ID
			msg.Content = envResp.Response.MsgQ.Msg
			msg.QueueDepth = envResp.Response.MsgQ.Count
		}

		return nil
	})

	return msg, err
}

