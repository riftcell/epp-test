// CheckHost sends a host:check command and returns availability for each name.
func (a *GenericEPPAdapter) CheckHost(ctx context.Context, names ...string) ([]registrar.HostResult, error) {
	normNames := make([]string, len(names))
	for i, name := range names {
		ace, err := registrar.NormalizeToACE(name)
		if err != nil {
			return nil, err //nolint:wrapcheck // *EPPError{Code:2005} carries full context
		}
		normNames[i] = ace
	}
	var results []registrar.HostResult

	err := a.withConn(ctx, func(conn net.Conn) error {
		clTRID := a.nextClTRID()
		env := eppxml.EPPEnvelope{
			Command: &eppxml.EPPCommand{
				HostCheck: &eppxml.HostCheckCommand{Names: normNames},
				ClTRID:    clTRID,
			},
		}

		envResp, err := sendAndReceive(conn, env)
		if err != nil {
			return fmt.Errorf("epp: host:check: %w", err)
		}

		if envResp.Response == nil {
			return fmt.Errorf("epp: host:check: response missing <epp:response>")
		}

		if err := a.resultToError(envResp.Response.Result, "host:check"); err != nil {
			return err
		}

		results = make([]registrar.HostResult, len(normNames))
		for i, n := range normNames {
			results[i] = registrar.HostResult{Name: n}
		}
		return nil
	})

	return results, err
}

